function summary = benchmark_boundary(profile,options)
arguments
    profile (1,:) char {mustBeMember(profile,{'quick','full'})} = 'quick'
    options.OutputRoot (1,:) char = fullfile(fileparts(mfilename('fullpath')),'..','results','robustness')
end
if ~exist(options.OutputRoot,'dir'), mkdir(options.OutputRoot); end
directory = tempname(options.OutputRoot); mkdir(directory);
cases = struct('name',{},'track',{},'duration',{},'experiment',{});
cases(end+1) = definition('baseline_chicane','chicane',40,struct());
cases(end+1) = definition('baseline_kidney','kidney',40,struct());
cases(end+1) = definition('noisy_lines','chicane',40,struct('line_noise',0.02,'obstacle_noise',0.02));
cases(end+1) = definition('sensor_latency','kidney',40,struct('latency_steps',3));
if strcmp(profile,'quick')
    for i = 1:numel(cases), cases(i).duration = 12; end
else
    cases(end+1) = definition('baseline_oval','oval',40,struct());
    cases(end+1) = definition('brief_marking_loss','chicane',40, ...
        struct('line_loss_start',2,'line_loss_end',2.8));
    cases(end+1) = definition('long_marking_loss','kidney',40, ...
        struct('line_loss_start',2,'line_loss_end',20));
    cases(end+1) = definition('missed_objects','chicane',40, ...
        struct('miss_probability',0.20,'obstacle_noise',0.01));
    cases(end+1) = definition('uncertain_classes','chicane',40, ...
        struct('uncertain_classification',true));
    cases(end+1) = definition('plant_mismatch','kidney',40, ...
        struct('plant_wheelbase_scale',1.15,'plant_acceleration_scale',0.9,'model_margin',0.02));
    cases(end+1) = definition('fast_crossers','chicane',40,struct('crossing_scale',1.5));
    cases(end+1) = definition('reversed_crossers','kidney',40, ...
        struct('crossing_direction',-1,'crossing_phase',0.7));
    cases(end+1) = definition('different_start','oval',40,struct('start_fraction',0.08));
    cases(end+1) = definition('larger_objects','chicane',40,struct('radius_scale',1.4));
    cases(end+1) = definition('combined_uncertainty','kidney',40, ...
        struct('line_noise',0.01,'obstacle_noise',0.01,'latency_steps',2, ...
        'miss_probability',0.10,'plant_wheelbase_scale',1.1,'model_margin',0.02));
    cases(end+1) = definition('deadline_watchdog','chicane',40,struct('enforce_deadline',true));
end
write_json(fullfile(directory,'cases.json'),struct('profile',profile,'cases',cases, ...
    'fairness','same world and indexed exogenous draws; perception depends on vehicle trajectory', ...
    'scope','simulation only; no hardware ROS2 or external simulator integration', ...
    'status','running'));
warmup = zeros(2,1); controllers = {'laguerre';'ltv'};
for i = 1:2
    started = tic;
    run_boundary_demo('chicane',Duration=1,Controller=controllers{i},Save=false);
    warmup(i) = toc(started);
end
writetable(table(controllers,warmup,'VariableNames',{'controller','cold_warmup_wall_s'}), ...
    fullfile(directory,'warmup.csv'));
rows = struct([]);
for i = 1:numel(cases)
    test = cases(i);
    order = controllers;
    if mod(i,2)==0, order = flipud(order); end
    for j = 1:2
        controller = order{j};
        fprintf('Robustness %d/%d: %s / %s\n',2*(i-1)+j,2*numel(cases),test.name,controller);
        started = tic;
        result = run_boundary_demo(test.track,Duration=test.duration,Controller=controller, ...
            Experiment=test.experiment,OutputRoot=fullfile(directory,'runs'));
        m = result.metrics;
        row = struct('case_name',test.name,'track',test.track,'controller',controller, ...
            'seed',result.seed,'success',m.success,'safety_pass',m.safety_pass, ...
            'termination',m.termination,'duration_s',m.duration, ...
            'requested_duration_s',test.duration,'laps',m.laps,'required_laps',m.required_laps, ...
            'path_error_rms_cm',100*m.path_error_rms, ...
            'clearance_cm',100*m.min_clearance,'road_clearance_cm',100*m.min_road_clearance, ...
            'contacts',m.confirmed_contact_steps,'road_departures',m.road_departure_steps, ...
            'yielding_steps',m.yielding_steps,'fallback_steps',m.fallback_steps, ...
            'solver_failures',m.solver_failures,'resume_events',m.resume_events, ...
            'max_stopped_s',m.max_stopped_duration,'variables',max(result.logs.variables), ...
            'solve_median_ms',1000*m.solve_time_median,'solve_p99_ms',1000*m.solve_time_p99, ...
            'online_p99_ms',1000*m.online_time_p99,'step_p99_ms',1000*m.step_time_p99, ...
            'sensor_p99_ms',1000*m.sensor_time_p99,'planning_p99_ms',1000*m.planning_time_p99, ...
            'validation_p99_ms',1000*m.validation_time_p99, ...
            'monitor_p99_ms',1000*m.physics_monitor_time_p99, ...
            'missed_online_deadlines',m.missed_online_deadlines, ...
            'missed_step_deadlines',m.missed_step_deadlines, ...
            'deadline_interventions',m.deadline_interventions,'replans',m.replans, ...
            'ticks',height(result.logs),'wall_time_s',toc(started), ...
            'run_directory',result.run_dir);
        rows = [rows;row]; %#ok<AGROW>
        summary = struct2table(rows);
        writetable(summary,fullfile(directory,'summary.csv'));
        save(fullfile(directory,'benchmark.mat'),'cases','summary','profile');
    end
end
write_json(fullfile(directory,'cases.json'),struct('profile',profile,'cases',cases, ...
    'fairness','same world and indexed exogenous draws; perception depends on vehicle trajectory', ...
    'scope','simulation only; no hardware ROS2 or external simulator integration', ...
    'status','completed'));
fprintf('ROBUSTNESS_DIRECTORY=%s\n',directory);
disp(summary(:,{'case_name','controller','success','safety_pass','termination','laps','step_p99_ms'}));
end

function test = definition(name,track,duration,experiment)
test = struct('name',name,'track',track,'duration',duration, ...
    'experiment',boundary_experiment_parameters(experiment));
end

function write_json(path,value)
file = fopen(path,'w');
if file<0, error('mpc:SaveFailed','Cannot create %s.',path); end
cleanup = onCleanup(@() fclose(file));
fprintf(file,'%s\n',jsonencode(value,'PrettyPrint',true));
end
